function progressTimeline(
  prefix: string,
  finalStatus: ShipmentStatus,
  startDay: number,
  actorIds: { sender: string; traveler?: string },
): TimelineEvent[] {
  const path = TIMELINE_PATHS[finalStatus];
  return path.map((status, index) => {
    const meta = TIMELINE_LABELS[status];
    const actorId =
      meta.actor === "traveler"
        ? actorIds.traveler
        : meta.actor === "sender"
          ? actorIds.sender
          : undefined;
    return timelineEvent(
      `${prefix}-tl-${status}`,
      status,
      { bn: meta.bn, en: meta.en },
      startDay + index,
      0,
      actorId,
    );
  });
}

